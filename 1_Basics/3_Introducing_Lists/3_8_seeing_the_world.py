str_places = ["Egypt","Mount Rushmore","Grand Canyan","Ayodhya","Vrindavan"]

#print the list

print(str_places)

#Use sorted()

print(sorted(str_places))

#print original list

print(str_places)

#print reverse sorted list

print(sorted(str_places, reverse=True))

#print original list

print(str_places)

str_places.reverse()

#Printing reversed list

print(str_places)

#reverse the order of the list again

str_places.reverse()

#Confirm that the list has permanently changed

print(str_places)

#use Sort() to change the list to sort alphabetically

str_places.sort()

#print the sorted list

print(str_places)

#sort the list in reverse alphabetical order

str_places.sort(reverse=True)

print(str_places)

